BEGIN;

ALTER TABLE ubicaciones
  ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE carros
  ADD COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN ubicacion_internal_id BIGINT;

UPDATE carros c
SET ubicacion_internal_id = u.id
FROM ubicaciones u
WHERE c.ubicacion = u.slug;

ALTER TABLE notebooks ADD COLUMN carro_internal_id BIGINT;
UPDATE notebooks n
SET carro_internal_id = c.id
FROM carros c
WHERE n.carro_id = c.numero;

ALTER TABLE carros DROP CONSTRAINT IF EXISTS carros_ubicacion_fkey;
ALTER TABLE carros DROP CONSTRAINT IF EXISTS carros_ubicacion_check;
ALTER TABLE notebooks DROP CONSTRAINT IF EXISTS notebooks_carro_id_fkey;

ALTER TABLE carros ADD CONSTRAINT carros_numero_key UNIQUE (numero);
ALTER TABLE ubicaciones ADD CONSTRAINT ubicaciones_slug_key UNIQUE (slug);
ALTER TABLE carros DROP CONSTRAINT carros_pkey;
ALTER TABLE ubicaciones DROP CONSTRAINT ubicaciones_pkey;

ALTER TABLE carros DROP COLUMN ubicacion;
ALTER TABLE carros RENAME COLUMN ubicacion_internal_id TO ubicacion_id;
ALTER TABLE notebooks DROP COLUMN carro_id;
ALTER TABLE notebooks RENAME COLUMN carro_internal_id TO carro_id;

ALTER TABLE carros ADD CONSTRAINT carros_pkey PRIMARY KEY (id);
ALTER TABLE ubicaciones ADD CONSTRAINT ubicaciones_pkey PRIMARY KEY (id);
ALTER TABLE carros ADD CONSTRAINT carros_ubicacion_id_fkey
  FOREIGN KEY (ubicacion_id) REFERENCES ubicaciones(id);
ALTER TABLE notebooks ADD CONSTRAINT notebooks_carro_id_fkey
  FOREIGN KEY (carro_id) REFERENCES carros(id);

CREATE INDEX IF NOT EXISTS carros_ubicacion_id_idx ON carros(ubicacion_id);
CREATE INDEX IF NOT EXISTS notebooks_carro_estado_idx ON notebooks(carro_id, estado);

COMMIT;
